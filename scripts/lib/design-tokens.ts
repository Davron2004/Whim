// ── Formatting ───────────────────────────────────────────────────────────────

const code = (s: string | number) => '`' + s + '`';
const fixed = (n: number, digits: number) => n.toFixed(digits);

/** A Markdown table row; an empty cell renders as a single space, as hand-written tables do. */
const row = (cells: readonly (string | number)[]) => '|' + cells.map((c) => (c === '' ? ' ' : ` ${c} `)).join('|') + '|';
const header = (cells: readonly string[]) => [row(cells), '|' + cells.map(() => '---').join('|') + '|'];

/** `a` / `b`, or `a` both when the two schemes agree. */
const pairCell = (p: Pair) => (p.light === p.dark ? `${code(p.light)} both` : `${code(p.light)} / ${code(p.dark)}`);

function signedEm(n: number): string {
  if (n === 0) return '0';
  return (n < 0 ? '−' : '+') + fixed(Math.abs(n), 3);
}

// ── Contrast ─────────────────────────────────────────────────────────────────

/** The lowest contrast of `fg` over `on` in `scheme`. */
function minContrast(scheme: Scheme, fg: ColorRole, on: readonly ColorRole[]): number {
  return Math.min(...on.map((bg) => contrastRatio(COLORS[scheme][fg], COLORS[scheme][bg])));
}

/** "4.66 / 5.97 on `bg`, `fill`" for the rule on `fg`, or '' when §2 specifies none. */
function contrastCell(fg: ColorRole): string {
  const rule = CONTRAST_RULES.find((r) => r.fg === fg);
  if (rule === undefined) return '';
  const at = rule.on.length > 1 ? '≥ ' : '';
  const [l, d] = (['light', 'dark'] as const).map((s) => at + fixed(minContrast(s, fg, rule.on), 2));
  return `${l} / ${d} on ${rule.on.map(code).join(', ')}`;
}

