/** Every file `npm run tokens` writes or splices, repo-relative. */
export const OUTPUT_FILES: readonly string[] = [...Object.keys(REGIONS), ...Object.keys(WHOLE_FILES)];

export interface Drift {
  readonly file: string;
  readonly region?: string;
  readonly message: string;
}

interface Span {
  readonly begin: number;
  readonly end: number;
}

function findRegion(lines: readonly string[], name: string): Span | undefined {
  const marker = (kind: string) => new RegExp(`tokens:${kind} ${name}(?![\\w-])`);
  const begin = lines.findIndex((l) => marker('begin').test(l));
  const end = lines.findIndex((l, i) => i > begin && marker('end').test(l));
  return begin < 0 || end < 0 ? undefined : { begin, end };
}

/** Where `actual` first departs from `expected`: for a Markdown table row, the row, the column and
 *  both cell values; otherwise the line and both texts. */
function describeDifference(expected: readonly string[], actual: readonly string[]): string {
  const i = expected.findIndex((line, k) => line !== actual[k]);
  const at = i < 0 ? expected.length : i;
  const want = expected[at];
  const got = actual[at];
  if (want === undefined) return `an extra line ${JSON.stringify(got)} the token module does not give`;
  if (got === undefined) return `a missing line; the token module gives ${JSON.stringify(want)}`;
  if (want.startsWith('|') && got.startsWith('|')) {
    const cells = (l: string) => l.split('|').slice(1, -1).map((c) => c.trim());
    const [w, g] = [cells(want), cells(got)];
    const col = w.findIndex((c, k) => c !== g[k]);
    if (col >= 0) {
      const columns = cells(expected[0]);
      return `row ${w[0]}, column "${columns[col] ?? col + 1}": the file has ${JSON.stringify(g[col] ?? '')}, the token module gives ${JSON.stringify(w[col])}`;
    }
  }
  return `line ${at + 1}: the file has ${JSON.stringify(got)}, the token module gives ${JSON.stringify(want)}`;
}

/** `text` with each of `regions` regenerated between its markers; a missing marker is a problem. */
function spliceRegions(file: string, text: string, regions: Readonly<Record<string, () => string[]>>, problems: Drift[]): string {
  let lines = text.split('\n');
  for (const [name, render] of Object.entries(regions)) {
    const span = findRegion(lines, name);
    if (span === undefined) problems.push({ file, region: name, message: `no "tokens:begin ${name}" … "tokens:end ${name}" markers` });
    else lines = [...lines.slice(0, span.begin + 1), ...render(), ...lines.slice(span.end)];
  }
  return lines.join('\n');
}

/** Each output file's generated text, given the current text of the files with marked regions
 *  (`read` returns undefined for a missing file). A missing file or marker is a drift. */
export function renderOutputs(read: (file: string) => string | undefined): { files: Record<string, string>; problems: Drift[] } {
  const files: Record<string, string> = {};
  const problems: Drift[] = [];
  for (const [file, regions] of Object.entries(REGIONS)) {
    const text = read(file);
    if (text === undefined) problems.push({ file, message: 'the file is missing' });
    else files[file] = spliceRegions(file, text, regions, problems);
  }
  for (const [file, render] of Object.entries(WHOLE_FILES)) files[file] = render();
  return { files, problems };
}

/** Every output that differs from what the token module gives, naming where and both values. */
export function checkOutputs(read: (file: string) => string | undefined): Drift[] {
  const { files, problems } = renderOutputs(read);
  const drifts = [...problems];
  for (const [file, expected] of Object.entries(files)) {
    const actual = read(file);
    if (actual === expected) continue;
    if (actual === undefined) {
      drifts.push({ file, message: 'the file is missing' });
      continue;
    }
    const regions = REGIONS[file];
    if (regions === undefined) {
      drifts.push({ file, message: describeDifference(expected.split('\n'), actual.split('\n')) });
      continue;
    }
    const [want, got] = [expected.split('\n'), actual.split('\n')];
    for (const name of Object.keys(regions)) {
      const w = findRegion(want, name);
      const g = findRegion(got, name);
      if (w === undefined || g === undefined) continue;
      const wantBody = want.slice(w.begin + 1, w.end);
      const gotBody = got.slice(g.begin + 1, g.end);
      if (wantBody.join('\n') !== gotBody.join('\n')) drifts.push({ file, region: name, message: describeDifference(wantBody, gotBody) });
    }
  }
  return drifts;
}

/** One line per drift, for the CLI and the gate. */
export function formatDrift(d: Drift): string {
  const where = d.region === undefined ? d.file : `${d.file} [${d.region}]`;
  return `${where}: ${d.message}`;
}
