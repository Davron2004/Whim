// ── Spring sampling ──────────────────────────────────────────────────────────

const FPS = 60;
/** Settled: within 0.1% of the distance, moving under 1% of it per second, from this frame on. */
const SETTLE_DISTANCE = 0.001;
const SETTLE_VELOCITY = 0.01;
const HORIZON_S = 5;

export interface SampledSpring {
  readonly durationMs: number;
  readonly t95Ms: number;
  readonly overshoot: number;
  readonly linear: string;
  readonly cubicBezier: string;
}

/** Position (0 → 1) and velocity at `t` seconds of a mass-1 spring released from rest. */
function stepResponse(s: Spring, t: number): [number, number] {
  const w = (2 * Math.PI) / s.response;
  const z = s.dampingRatio;
  if (z === 1) {
    const e = Math.exp(-w * t);
    return [1 - (1 + w * t) * e, w * w * t * e];
  }
  if (z < 1) {
    const wd = w * Math.sqrt(1 - z * z);
    const e = Math.exp(-z * w * t);
    return [1 - e * (Math.cos(wd * t) + ((z * w) / wd) * Math.sin(wd * t)), e * ((w * w) / wd) * Math.sin(wd * t)];
  }
  const root = w * Math.sqrt(z * z - 1);
  const r1 = -z * w + root;
  const r2 = -z * w - root;
  const e1 = Math.exp(r1 * t);
  const e2 = Math.exp(r2 * t);
  return [1 + (r2 * e1 - r1 * e2) / (r1 - r2), (r1 * r2 * (e1 - e2)) / (r1 - r2)];
}

const round3 = (n: number) => {
  const r = Math.round(n * 1000) / 1000;
  return r === 0 ? 0 : r;
};

function settledFrame(s: Spring): number {
  let last = 0;
  for (let f = 0; f <= HORIZON_S * FPS; f++) {
    const [x, v] = stepResponse(s, f / FPS);
    if (Math.abs(x - 1) >= SETTLE_DISTANCE || Math.abs(v) >= SETTLE_VELOCITY) last = f;
  }
  return last + 1;
}

function time95(s: Spring): number {
  let hi = 1 / FPS;
  while (stepResponse(s, hi)[0] < 0.95) hi += 1 / FPS;
  let lo = hi - 1 / FPS;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (stepResponse(s, mid)[0] < 0.95) lo = mid;
    else hi = mid;
  }
  return hi;
}

/** CSS cubic-bezier(x1, y1, x2, y2) at progress `u` (0–1). */
function bezierAt(p: readonly number[], u: number): number {
  const [x1, y1, x2, y2] = p;
  const coord = (a: number, b: number, s: number) => 3 * a * (1 - s) ** 2 * s + 3 * b * (1 - s) * s * s + s ** 3;
  let lo = 0;
  let hi = 1;
  for (let i = 0; i < 30; i++) {
    const mid = (lo + hi) / 2;
    if (coord(x1, x2, mid) < u) lo = mid;
    else hi = mid;
  }
  return coord(y1, y2, (lo + hi) / 2);
}

function fitError(p: readonly number[], samples: readonly number[]): number {
  const n = samples.length - 1;
  let sum = 0;
  for (let i = 0; i <= n; i++) sum += (bezierAt(p, i / n) - samples[i]) ** 2;
  return sum;
}

const FIT_STARTS = [
  [0.25, 0.5, 0.25, 1],
  [0.2, 0.9, 0.2, 1],
  [0.4, 0, 0.2, 1],
  [0.3, 1.3, 0.3, 1],
  [0.5, 0.5, 0, 1],
];

/** The cubic-bezier nearest the sampled curve (least squares), by a deterministic pattern search
 *  ending on the 0.01 grid it is printed at. A curve that never passes its target gets a bezier
 *  that never does either (both y control points at most 1). */
function nearestCubicBezier(samples: readonly number[]): string {
  const yMax = Math.max(...samples) > 1 ? Infinity : 1;
  const within = (v: number, hi: number) => Math.min(hi, Math.max(0, v));
  const clamp = (p: number[]) => [within(p[0], 1), Math.min(yMax, p[1]), within(p[2], 1), Math.min(yMax, p[3])];
  // The first of the eight one-coordinate moves of `step` that lowers the error, if any.
  const betterNeighbour = (from: number[], error: number, step: number): [number[], number] | undefined => {
    for (let k = 0; k < 4; k++) {
      for (const dir of [1, -1]) {
        const cand = clamp(from.map((v, i) => (i === k ? Math.round((v + dir * step) * 100) / 100 : v)));
        const e = fitError(cand, samples);
        if (e < error - 1e-12) return [cand, e];
      }
    }
    return undefined;
  };
  const descend = (start: number[]): [number[], number] => {
    let at: [number[], number] = [clamp(start), fitError(clamp(start), samples)];
    for (let step = 0.16; step >= 0.01 - 1e-9; step /= 2) {
      for (let next = betterNeighbour(at[0], at[1], step); next !== undefined; next = betterNeighbour(at[0], at[1], step)) at = next;
    }
    return at;
  };
  // Several starts, so a local minimum of one does not decide the curve; the lowest error wins.
  const [best] = FIT_STARTS.map(descend).reduce((a, b) => (b[1] < a[1] - 1e-12 ? b : a));
  return `cubic-bezier(${best.map((v) => String(Math.round(v * 100) / 100)).join(', ')})`;
}

const sampleCache = new Map<Spring, SampledSpring>();

/** A spring sampled at 60 Hz until it settles. */
export function sampleSpring(s: Spring): SampledSpring {
  const cached = sampleCache.get(s);
  if (cached !== undefined) return cached;
  const frames = settledFrame(s);
  const samples = Array.from({ length: frames + 1 }, (_, f) => (f === frames ? 1 : stepResponse(s, f / FPS)[0]));
  const z = s.dampingRatio;
  const sampled: SampledSpring = {
    durationMs: Math.round((frames * 1000) / FPS),
    t95Ms: Math.round(time95(s) * 1000),
    overshoot: z < 1 ? round3(Math.exp((-z * Math.PI) / Math.sqrt(1 - z * z))) : 0,
    linear: `linear(${samples.map((x) => String(round3(x))).join(', ')})`,
    cubicBezier: nearestCubicBezier(samples),
  };
  sampleCache.set(s, sampled);
  return sampled;
}

