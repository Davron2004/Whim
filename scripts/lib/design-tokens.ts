/** The reserved colours a tint must keep away from in `scheme`: every status fill and text form and
 *  the ember and its text form, each distinct value once. */
export function reservedColors(scheme: Scheme): Record<string, string> {
  const out: Record<string, string> = {};
  const add = (name: string, value: string) => {
    if (!Object.values(out).includes(value)) out[name] = value;
  };
  for (const name of STATUS_NAMES) {
    add(name, STATUS[name].fill[scheme]);
    add(`${name}-text`, STATUS[name].text[scheme]);
  }
  add('ember', EMBER_ROLES.ember[scheme]);
  add('ember-text', EMBER_ROLES['ember-text'][scheme]);
  return out;
}

/** The dark-mode tile rim colour of a tint. */
